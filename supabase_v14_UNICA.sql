-- B. ADMIN · CAMBIAR ALUMNO ↔ PROFESOR DESDE EL AULA
-- ==========================================================

create or replace function public.admin_set_user_role(
  target_user_id uuid,
  new_role text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_target_role text;
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if not public.is_admin() then
    raise exception 'Sólo un administrador puede cambiar roles';
  end if;

  if new_role not in ('student','teacher') then
    raise exception 'Rol no permitido';
  end if;

  select role
  into current_target_role
  from public.profiles
  where id = target_user_id;

  if current_target_role is null then
    raise exception 'Usuario no encontrado';
  end if;

  if current_target_role = 'admin' then
    raise exception 'Los administradores no se modifican desde esta opción';
  end if;

  update public.profiles
  set role = new_role
  where id = target_user_id;
end;
$$;

revoke all on function public.admin_set_user_role(uuid,text) from public;
grant execute on function public.admin_set_user_role(uuid,text) to authenticated;

