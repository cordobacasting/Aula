create table if not exists public.challenge_cards (
  id bigint generated by default as identity primary key,
  category text not null,
  duration_label text,
  focus text not null,
  prompt text not null,
  rules jsonb not null default '[]'::jsonb,
  dialogue_lines jsonb not null default '[]'::jsonb,
  position integer not null default 1,
  is_published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.challenge_attempts (
  id bigint generated by default as identity primary key,
  challenge_id bigint not null references public.challenge_cards(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  dialogue_line text not null,
  submission_url text not null,
  reflection text,
  status text not null default 'submitted'
    check (status in ('submitted','reviewed','completed')),
  feedback text,
  reviewed_by uuid references public.profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.challenge_cards enable row level security;
alter table public.challenge_attempts enable row level security;

drop policy if exists "Authenticated read published challenges" on public.challenge_cards;
create policy "Authenticated read published challenges"
on public.challenge_cards
for select
to authenticated
using (is_published or public.is_admin());

drop policy if exists "Admin manages challenges" on public.challenge_cards;
create policy "Admin manages challenges"
on public.challenge_cards
for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "Users read own challenge attempts" on public.challenge_attempts;
create policy "Users read own challenge attempts"
on public.challenge_attempts
for select
to authenticated
using (user_id = auth.uid() or public.is_admin());

drop policy if exists "Users submit own challenges" on public.challenge_attempts;
create policy "Users submit own challenges"
on public.challenge_attempts
for insert
to authenticated
with check (
  user_id = auth.uid()
  and exists (
    select 1
    from public.challenge_cards c
    where c.id = challenge_id
      and c.is_published
  )
);

drop policy if exists "Admin reviews challenge attempts" on public.challenge_attempts;
create policy "Admin reviews challenge attempts"
on public.challenge_attempts
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

